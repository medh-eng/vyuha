/* Bundle reviewed catalogues for the PWA and portable file:// build. */
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
const root = fileURLToPath(new URL('../', import.meta.url));
const read = p => JSON.parse(fs.readFileSync(root + p, 'utf8'));
const data = { en: read('docs/i18n/strings.en.json'), hi: read('docs/i18n/strings.hi.json'), mr: read('docs/i18n/strings.mr.json') };
for (const lang of ['hi', 'mr']) assert.deepEqual(Object.keys(data[lang]), Object.keys(data.en), lang + ': catalogue keys/order');
for (const dictionary of Object.values(data)) for (const value of Object.values(dictionary)) assert.equal(typeof value, 'string');
const runtime = `
  let language = 'en';
  const cache = {};
  function setLang(value) {
    language = Object.prototype.hasOwnProperty.call(DATA, value) ? value : 'en';
    return language;
  }
  function text(key, fallback) {
    if (language === 'en' && fallback != null) return String(fallback);
    const value = DATA[language][key] != null ? DATA[language][key] : DATA.en[key];
    return typeof value === 'string' ? value : fallback != null ? String(fallback) : '';
  }
  function definition(group, key, prefix, fields) {
    const original = AC.units[group][key];
    if (!original) return original;
    const id = language + ':' + group + ':' + key;
    if (!cache[id]) {
      const copy = Object.assign({}, original);
      fields.forEach(function (field) { copy[field] = text(prefix + '.' + key + '.' + field, original[field]); });
      cache[id] = copy;
    }
    return cache[id];
  }
  function applyDOM(scope) {
    if (!root.document) return;
    root.document.documentElement.lang = language;
    const host = scope || root.document;
    host.querySelectorAll('[data-i18n]').forEach(function (el) {
      el.textContent = text(el.getAttribute('data-i18n')) || el.textContent;
    });
    host.querySelectorAll('[data-i18n-label]').forEach(function (el) {
      el.setAttribute('aria-label', text(el.getAttribute('data-i18n-label')) || el.getAttribute('aria-label'));
    });
  }
  AC.i18n = {
    text: text, setLang: setLang, getLang: function () { return language; }, applyDOM: applyDOM,
    languages: ['en', 'hi', 'mr'], keys: Object.keys(DATA.en),
    unit: function (key) { return definition('UNIT_DEFS', key, 'unit', ['role', 'one', 'desc', 'tip']); },
    astra: function (key) { return definition('ASTRA_DEFS', key, 'astra', ['one', 'desc']); },
    board: function (key) { return definition('BOARDS', key, 'board', ['blurb']); },
    opponent: function (key) { return definition('DIFFICULTIES', key, 'opponent', ['blurb']); },
    scenario: function (key) { return definition('SCENARIOS', key, 'scenario', ['blurb']); },
    daily: function (mod) { return Object.assign({}, mod, { name: text('daily.' + mod.key + '.name', mod.name), one: text('daily.' + mod.key + '.one', mod.one) }); },
    lesson: function (step, field) { return text('lesson.' + step.key + '.' + field, step[field]); }
  };
`;
const output = '/* Generated by tools/build-languages.mjs; edit source JSON, then rebuild. */\n(function (root) {\n  \'use strict\';\n  const AC = root.AC = root.AC || {};\n  const DATA = ' + JSON.stringify(data, null, 2).replace(/</g, '\\u003c') + ';\n' + runtime + '})(typeof globalThis !== \'undefined\' ? globalThis : this);\n';
fs.writeFileSync(root + 'js/languages.js', output);
console.log('Bundled ' + Object.keys(data.en).length + ' keys in English, Hindi and Marathi.');
